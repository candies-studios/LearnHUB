#!/usr/bin/env node
'use strict';
// Bundles the shared server logic (lib/*.js) with browser shims into pages/learnhub-local.js,
// which lets the GitHub Pages copy of LearnHub run with no server. Run after changing lib/ files:
//   node scripts/build-pages.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const mods = {
  crypto: 'pages/src/crypto-shim.js',
  './db': 'pages/src/db-browser.js',
  './util': 'lib/util.js',
  './core': 'lib/core.js',
  './chiller': 'lib/chiller.js',
  './routes': 'lib/routes.js',
  './cert': 'lib/cert.js',
  './local': 'pages/src/local-runtime.js',
};
let out = `/* LearnHub — in-browser build for GitHub Pages. GENERATED by scripts/build-pages.js — do not edit by hand. */
(function () {
'use strict';
var process = { env: {} };
var __defs = {}, __cache = {};
function require(name) {
  if (__cache[name]) return __cache[name].exports;
  if (!__defs[name]) throw new Error('LearnHub bundle: missing module ' + name);
  var module = (__cache[name] = { exports: {} });
  __defs[name](module, module.exports, require);
  return module.exports;
}
`;
for (const [name, file] of Object.entries(mods)) {
  const src = fs.readFileSync(path.join(root, file), 'utf8').replace(/^'use strict';\n/, '');
  out += `\n// ---- ${file}\n__defs[${JSON.stringify(name)}] = function (module, exports, require) {\n${src}\n};\n`;
}
out += `
var Buffer = { from: function (hex) { return new (require('crypto').HexBuf)(hex); } };
window.LearnHubLocal = require('./local');
})();
`;
fs.writeFileSync(path.join(root, 'pages/learnhub-local.js'), out);
console.log('Wrote pages/learnhub-local.js (' + Math.round(out.length / 1024) + ' KB)');
